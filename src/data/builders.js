export function getBuilderBySlug(slug) {
  return builders.find((b) => b.slug === slug) || null
}

export function getBuilderByName(name) {
  if (!name) return null
  const lower = name.toLowerCase()
  return builders.find((b) => b.name.toLowerCase().includes(lower) || lower.includes(b.name.toLowerCase().split(' ')[0].toLowerCase())) || null
}

